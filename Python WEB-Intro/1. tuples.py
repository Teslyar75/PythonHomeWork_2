"""
КОРТЕЖИ (TUPLES) - Незмінна послідовність елементів

Кортеж(tuple) – це тип даних, який зберігає впорядкований набір або послідовність елементів.
Це колекція, яка зберігає незмінну (immutable) послідовність елементів.
Після створення кортежу, ви НЕ можете змінювати, додавати або видаляти його елементи.

Переваги кортежів:
- Швидша робота порівняно зі списками
- Захист даних від випадкової зміни
- Можуть бути ключами словників (списки - ні)
- Використовують менше пам'яті
"""

# ============================================================
# СТВОРЕННЯ КОРТЕЖІВ
# ============================================================

# Кортеж з елементами
my_tuple = (1, 2, 3, 4, 5)
print("Кортеж:", my_tuple)

# Кортеж можна створити без дужок
tuple_without_brackets = 1, 2, 3, 4, 5
print("Кортеж без дужок:", tuple_without_brackets)

# Порожній кортеж
empty_tuple = ()
print("Порожній кортеж:", empty_tuple)

# Кортеж з одним елементом (ВАЖЛИВО: потрібна кома!)
single_element_tuple = (42,)  # Правильно
not_a_tuple = (42)  # Це просто число в дужках, не кортеж!
print("Кортеж з одним елементом:", single_element_tuple, type(single_element_tuple))
print("Не кортеж:", not_a_tuple, type(not_a_tuple))

# Кортеж з різними типами даних
mixed_tuple = (1, "Hello", 3.14, True, [1, 2, 3])
print("Змішаний кортеж:", mixed_tuple)

# Вкладені кортежі
nested_tuple = (1, 2, (3, 4, 5), (6, (7, 8)))
print("Вкладений кортеж:", nested_tuple)
print("Доступ до вкладеного елементу:", nested_tuple[2][1])  # Output: 4

# Створення кортежу за допомогою tuple()
tuple_from_list = tuple([1, 2, 3, 4, 5])
tuple_from_string = tuple("Hello")
print("Кортеж зі списку:", tuple_from_list)
print("Кортеж зі рядка:", tuple_from_string)

# ============================================================
# ОСНОВНІ ОПЕРАЦІЇ З КОРТЕЖАМИ
# ============================================================

# len() - повертає кількість елементів будь-якої послідовності
length = len(my_tuple)
print("\nДовжина кортежу:", length)

# Доступ до елементів за індексом (індексація починається з 0)
print("\nПерший елемент:", my_tuple[0])      # Output: 1
print("Останній елемент:", my_tuple[-1])     # Output: 5
print("Передостанній:", my_tuple[-2])        # Output: 4

# Зрізи (slices) [start:stop:step]
print("\n--- ЗРІЗИ ---")
print("Всі елементи:", my_tuple[:])          # Output: (1, 2, 3, 4, 5)
print("З 1 по 3:", my_tuple[1:4])            # Output: (2, 3, 4)
print("Перші 3:", my_tuple[:3])              # Output: (1, 2, 3)
print("Останні 2:", my_tuple[-2:])           # Output: (4, 5)
print("Кожен другий:", my_tuple[::2])        # Output: (1, 3, 5)
print("Реверс:", my_tuple[::-1])             # Output: (5, 4, 3, 2, 1)
print("Кожен другий з кінця:", my_tuple[::-2])  # Output: (5, 3, 1)

# ============================================================
# МЕТОДИ КОРТЕЖІВ
# ============================================================

print("\n--- МЕТОДИ КОРТЕЖІВ ---")

# index(value, start, stop) – пошук індексу за значенням
print("Індекс елемента 3:", my_tuple.index(3))  # Output: 2

# Пошук з визначеною позицією
tuple_with_repeats = (1, 2, 3, 2, 4, 2, 5)
print("Перше входження 2:", tuple_with_repeats.index(2))  # Output: 1
print("Входження 2 після індексу 2:", tuple_with_repeats.index(2, 2))  # Output: 3

# count(value) – повертає кількість повторень значення у кортежі
print("Кількість входжень 2:", tuple_with_repeats.count(2))  # Output: 3
print("Кількість входжень 10:", tuple_with_repeats.count(10))  # Output: 0

# ============================================================
# ІТЕРАЦІЯ ПО КОРТЕЖУ
# ============================================================

print("\n--- ІТЕРАЦІЯ ПО КОРТЕЖУ ---")

# Обробка елементів кортежу за допомогою циклу for
print("Проходження по значеннях:")
for value in my_tuple:
    print("  Значення:", value)

# range(start, stop, step) - функція, яка повертає послідовність чисел у зазначеному діапазоні
print("\nПроходження з індексами:")
for i in range(length):
    print(f"  Індекс: {i}, Значення: {my_tuple[i]}")

# Використання enumerate() для отримання індексу та значення одночасно
print("\nВикористання enumerate():")
for index, value in enumerate(my_tuple):
    print(f"  Індекс: {index}, Значення: {value}")

# ============================================================
# ОПЕРАЦІЇ З КОРТЕЖАМИ
# ============================================================

print("\n--- ОПЕРАЦІЇ З КОРТЕЖАМИ ---")

# Конкатенація (об'єднання)
tuple1 = (1, 2, 3)
tuple2 = (4, 5, 6)
combined = tuple1 + tuple2
print("Об'єднання кортежів:", combined)  # Output: (1, 2, 3, 4, 5, 6)

# Множення
repeated = tuple1 * 3
print("Повторення кортежу:", repeated)  # Output: (1, 2, 3, 1, 2, 3, 1, 2, 3)

# Перевірка наявності елемента
print("3 є в кортежі?", 3 in tuple1)      # Output: True
print("10 є в кортежі?", 10 in tuple1)    # Output: False

# Мінімум та максимум
print("Мінімальне значення:", min(my_tuple))  # Output: 1
print("Максимальне значення:", max(my_tuple))  # Output: 5
print("Сума елементів:", sum(my_tuple))        # Output: 15

# ============================================================
# РОЗПАКУВАННЯ КОРТЕЖІВ (TUPLE UNPACKING)
# ============================================================

print("\n--- РОЗПАКУВАННЯ КОРТЕЖІВ ---")

# Базове розпакування
coordinates = (10, 20)
x, y = coordinates
print(f"X: {x}, Y: {y}")

# Обмін значеннями змінних (елегантний спосіб без третьої змінної)
a = 5
b = 2
print(f"До обміну: a={a}, b={b}")
(a, b) = (b, a)  # Або просто: a, b = b, a
print(f"Після обміну: a={a}, b={b}")

# Розпакування з * (збирає залишок елементів)
numbers = (1, 2, 3, 4, 5, 6, 7)
first, second, *rest = numbers
print(f"Перший: {first}, Другий: {second}, Решта: {rest}")

first, *middle, last = numbers
print(f"Перший: {first}, Середина: {middle}, Останній: {last}")

# Ігнорування значень за допомогою _
point_3d = (10, 20, 30)
x, _, z = point_3d  # Ігноруємо Y-координату
print(f"X: {x}, Z: {z}")

# Розпакування вкладених кортежів
person = ("John", "Doe", (25, 12, 1990))
first_name, last_name, (day, month, year) = person
print(f"{first_name} {last_name}, народився {day}.{month}.{year}")

# ============================================================
# КОРТЕЖІ ЯК КЛЮЧІ СЛОВНИКА
# ============================================================

print("\n--- КОРТЕЖІ ЯК КЛЮЧІ СЛОВНИКА ---")

# Кортежі можна використовувати як ключі словника (списки - НІ!)
locations = {
    (0, 0): "Початок",
    (1, 0): "Схід",
    (0, 1): "Північ",
    (-1, 0): "Захід",
    (0, -1): "Південь"
}
print("Локації:", locations)
print("Локація (1, 0):", locations[(1, 0)])

# ============================================================
# КОРИСНІ ПРИКЛАДИ ВИКОРИСТАННЯ
# ============================================================

print("\n--- ПРАКТИЧНІ ПРИКЛАДИ ---")

# Повернення декількох значень з функції
def get_user_info():
    name = "Alice"
    age = 30
    email = "alice@example.com"
    return name, age, email  # Повертається кортеж

user_name, user_age, user_email = get_user_info()
print(f"Користувач: {user_name}, Вік: {user_age}, Email: {user_email}")

# Множинне присвоєння
min_value, max_value, default_value = 0, 100, 50
print(f"Min: {min_value}, Max: {max_value}, Default: {default_value}")

# Сортування кортежів
students = [
    ("Alice", 85),
    ("Bob", 90),
    ("Charlie", 78),
    ("Diana", 95)
]
students.sort(key=lambda x: x[1], reverse=True)  # Сортування за оцінкою
print("Топ студентів:", students)

print("\n✓ Кортежі - це ефективний спосіб зберігання незмінних даних!")

    